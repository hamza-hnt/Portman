#!/bin/sh
# Build a real, checksummed local tap without inventing an unpublished upstream.
set -eu

command -v brew >/dev/null 2>&1 || { echo "Install Homebrew first: https://brew.sh" >&2; exit 1; }
test "$(uname -s)" = Darwin || { echo "This Homebrew installer is for macOS; use ./install.sh on Linux." >&2; exit 1; }
task_root=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
task_tap="portman/local"
task_tap_dir="$(brew --repository)/Library/Taps/portman/homebrew-local"
task_version=$(cat "$task_root/VERSION")
task_cache="$(brew --cache)/portman-source"
mkdir -p "$task_cache"
task_temp=$(mktemp -d)
trap 'rm -rf "$task_temp"' EXIT HUP INT TERM

cd "$task_root"
COPYFILE_DISABLE=1 tar -czf "$task_temp/source.tar.gz" go.mod go.sum cmd internal Makefile VERSION install.sh README.md LICENSE docs scripts assets .github .gitignore
task_sha=$(shasum -a 256 "$task_temp/source.tar.gz" | cut -d ' ' -f 1)
task_archive="$task_cache/portman-$task_version-$task_sha.tar.gz"
mv "$task_temp/source.tar.gz" "$task_archive"

if ! test -d "$task_tap_dir"; then
  HOMEBREW_DEVELOPER=1 HOMEBREW_NO_AUTO_UPDATE=1 brew tap-new --no-git "$task_tap"
fi
mkdir -p "$task_tap_dir/Formula"
task_formula="$task_tap_dir/Formula/portman.rb"
if test -e "$task_formula"; then
  case "$(head -n 1 "$task_formula")" in
    '# Generated by Portman'*) ;;
    *) echo "Refusing to overwrite an existing, unrelated formula: $task_formula" >&2; exit 1 ;;
  esac
fi

# Ruby string serialization prevents paths containing quotes from becoming code.
PORTMAN_ARCHIVE="$task_archive" PORTMAN_SHA="$task_sha" PORTMAN_FORMULA="$task_formula" PORTMAN_VERSION="$task_version" /usr/bin/ruby <<'RUBY'
require "uri"
url = "file://" + URI::DEFAULT_PARSER.escape(ENV.fetch("PORTMAN_ARCHIVE"))
File.write(ENV.fetch("PORTMAN_FORMULA"), <<~FORMULA)
  # Generated by Portman local installer; safe to regenerate.
  class Portman < Formula
    desc "Discover, monitor, and safely manage local ports and projects"
    url #{url.dump}
    version #{ENV.fetch("PORTMAN_VERSION").dump}
    sha256 #{ENV.fetch("PORTMAN_SHA").dump}
    license "MIT"
    depends_on "go" => :build
    depends_on :macos

    def install
      ENV["CGO_ENABLED"] = "1"
      system "go", "build", *std_go_args(ldflags: "-s -w -X main.version=\#{version}"), "./cmd/portman"
    end

    test do
      assert_match version.to_s, shell_output("\#{bin}/portman --version")
      assert_match '"processes":', shell_output("\#{bin}/portman --json")
    end
  end
FORMULA
RUBY

echo "Prepared $task_formula"
if test "${1:-}" = "--prepare-only"; then exit 0; fi
if HOMEBREW_NO_AUTO_UPDATE=1 brew list --formula "$task_tap/portman" >/dev/null 2>&1; then
  HOMEBREW_NO_AUTO_UPDATE=1 brew reinstall --build-from-source "$task_tap/portman"
else
  HOMEBREW_NO_AUTO_UPDATE=1 brew install --build-from-source "$task_tap/portman"
fi
